// Generates the extension signing key once. Public key + derived id are committed; private key stays in .keys/ (gitignored, back it up).
import { generateKeyPairSync, createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const out = path.join(root, "packages/extension/extension-id.json");
if (fs.existsSync(out)) { console.log("extension key already exists:", JSON.parse(fs.readFileSync(out, "utf8")).id); process.exit(0); }
const { publicKey, privateKey } = generateKeyPairSync("rsa", { modulusLength: 2048 });
const der = publicKey.export({ type: "spki", format: "der" });
const id = [...createHash("sha256").update(der).digest().subarray(0, 16)].map((b) => String.fromCharCode(97 + (b >> 4)) + String.fromCharCode(97 + (b & 15))).join("");
fs.mkdirSync(path.join(root, ".keys"), { recursive: true });
fs.writeFileSync(path.join(root, ".keys/extension-private.pem"), privateKey.export({ type: "pkcs8", format: "pem" }), { mode: 0o600 });
fs.writeFileSync(out, JSON.stringify({ id, key: der.toString("base64") }, null, 2) + "\n");
fs.writeFileSync(path.join(root, "packages/core/src/extension-id.ts"), `// generated by scripts/gen-extension-key.mjs\nexport const EXTENSION_ID = ${JSON.stringify(id)};\n`);
console.log("generated extension id", id);
